// Generates docs/fy2026-signoff-worksheet.md: for each parameter in a
// parameter file, the value, the quote, and where (if anywhere) the quote's
// text appears verbatim in the cited snapshot. This is a reading aid; it
// does not verify anything. See docs/parameter-verification.md.
import fs from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(process.cwd() + '/model/package.json');
let Y; try { Y = require('yaml'); } catch { Y = require('js-yaml'); }

const fy = process.argv[2] ?? 'fy2026';
const d = (Y.parse ?? Y.load)(fs.readFileSync(`model/parameters/${fy}.yaml`, 'utf8'));
const ps = d.parameters ?? d;
const norm = (s) => s.replace(/[“”]/g, '"').replace(/[‘’]/g, "'").replace(/\s+/g, ' ').trim();
const cache = {};
const snap = (p) => (cache[p] ??= fs.existsSync(p) ? fs.readFileSync(p, 'utf8').split('\n') : null);

const out = [];
out.push(`# ${fy.toUpperCase()} parameter sign-off worksheet`, '',
`Generated by \`scripts/signoff-worksheet.mjs\` from \`model/parameters/${fy}.yaml\`. A reading aid, not a verification: "found" only means a sentence from the file's \`quote\` appears in the snapshot, not that the value, structure or effective date are right.`, '',
'For each box: read the snapshot lines, then confirm **value**, **structure** (how `model/src/membership.ts` / `tax.ts` use it), and **in force for the fiscal year**. Then set `verified_by` to your name and `verified_date` to today in the YAML.', '');

let n = 0, todo = 0;
for (const [k, v] of Object.entries(ps)) {
  if (!v || typeof v !== 'object' || !v.citation) continue;
  n++;
  const c = v.citation, vb = String(c.verified_by ?? '');
  const awaiting = vb.includes('awaiting');
  if (awaiting) todo++;
  const snaps = (vb.match(/model\/statute\/[^;\s]+\.txt/g) ?? []);
  out.push(`## ${awaiting ? '[ ]' : '[x]'} \`${k}\` = ${JSON.stringify(v.value)} ${v.unit ?? ''}`, '',
    `- Statute: ${c.statute}${c.session_law ? ` — ${c.session_law}` : ''}`,
    `- Status: ${awaiting ? 'AWAITING countersignature' : 'signed: ' + vb} (${c.verified_date})`);
  if (v.structural_note) out.push(`- Structural note: ${norm(String(v.structural_note))}`);
  out.push('', '**Quote in file:**', '', ...String(c.quote).trim().split('\n').map((l) => '> ' + l.trim()), '');
  if (!snaps.length) {
    out.push(`**Snapshot:** none cited (${c.source_url}). Check the source by hand.`, '');
    continue;
  }
  // Split quote into sentences; look for each (first 70 chars) in the snapshot.
  const sentences = norm(String(c.quote)).split(/(?<=[.;:—])\s+/).filter((s) => s.length > 25);
  for (const sp of snaps) {
    const lines = snap(sp);
    if (!lines) { out.push(`**Snapshot** \`${sp}\`: file missing.`, ''); continue; }
    const nl = lines.map(norm);
    const hits = [];
    for (const s of sentences) {
      const key = s.slice(0, 28);
      const i = nl.findIndex((l) => l.includes(key));
      if (i >= 0) hits.push(i);
    }
    out.push(`**Snapshot** \`${sp}\` — ${hits.length}/${sentences.length} quote sentences found verbatim.`, '');
    if (hits.length) {
      const lo = Math.max(0, Math.min(...hits) - 1), hi = Math.min(lines.length - 1, Math.max(...hits) + 3);
      out.push('```text', ...lines.slice(lo, hi + 1).map((l, j) => `${String(lo + j + 1).padStart(4)}| ${l.slice(0, 220)}`), '```', '');
    } else out.push('_No match: the quote is paraphrase or commentary. Find the operative text by hand._', '');
    const ctg = lines.map((l, i) => [l, i]).filter(([l]) => /contingency|effective (July|until)|repeal/i.test(l)).slice(0, 6);
    if (ctg.length && /4010|4001/.test(sp)) out.push('_Effective-date flags in this snapshot:_ ' + ctg.map(([l, i]) => `L${i + 1}`).join(', '), '');
  }
}
out.push('---', `${todo} of ${n} awaiting countersignature.`);
fs.writeFileSync(`docs/${fy}-signoff-worksheet.md`, out.join('\n') + '\n');
console.log(`wrote docs/${fy}-signoff-worksheet.md: ${n} parameters, ${todo} awaiting`);
