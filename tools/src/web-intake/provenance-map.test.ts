import { describe, expect, it } from 'vitest';

import { buildProvenance } from '../intake/provenance.ts';
import { validateAgainst } from '../validate/schemas.ts';
import type { WebSubmission } from './payload.ts';
import { toSubmission } from './provenance-map.ts';

function ws(over: Partial<WebSubmission> = {}): WebSubmission {
  return {
    entity: 'su/addison-central',
    entityDir: 'su-addison-central',
    fiscalYear: 2025,
    sourceUrl: 'https://acsdvt.org/budget.pdf',
    retrievedDate: '2025-01-15',
    retrievalMethod: 'manual-download',
    documentType: 'budget_book',
    note: 'From the board packet.',
    submissionId: 'sub-1',
    source: { kind: 'upload', uploadId: 'up-1' },
    name: 'Pat Smith',
    ...over,
  };
}

const LINK = { kind: 'link', finalUrl: 'https://cdn.example.org/final.pdf', fetchedDate: '2026-11-22' } as const;

describe('toSubmission', () => {
  it('upload keeps contributor fields', () => {
    const s = toSubmission(ws(), 'budget.pdf', false, { kind: 'upload' });
    expect(s.sourceUrl).toBe('https://acsdvt.org/budget.pdf');
    expect(s.retrievedDate).toBe('2025-01-15');
    expect(s.retrievalMethod).toBe('manual-download');
    expect(s.note).toBe('From the board packet.');
    expect(s.attachmentUrl).toBe('netlify-blobs:up-1');
    expect(s.filename).toBe('budget.pdf');
  });

  it('link records http-fetch with fetch date and final url', () => {
    const s = toSubmission(ws({ source: { kind: 'link', url: 'https://x.org/a.pdf' } }), 'a.pdf', false, LINK);
    expect(s.retrievalMethod).toBe('http-fetch');
    expect(s.retrievedDate).toBe('2026-11-22');
    expect(s.sourceUrl).toBe('https://cdn.example.org/final.pdf');
    expect(s.attachmentUrl).toBe('https://x.org/a.pdf');
    expect(s.note).toContain('method manual-download');
    expect(s.note).toContain('date 2025-01-15');
    expect(s.note).toContain('source https://acsdvt.org/budget.pdf');
    expect(s.note).toContain('From the board packet.');
  });

  it('says source none when the contributor gave no source', () => {
    const s = toSubmission(ws({ sourceUrl: null, note: null }), 'a.pdf', false, LINK);
    expect(s.note).toBe('Sent through the web form. Contributor said: method manual-download, date 2025-01-15, source none.');
  });

  it('appends a sentence when the filename was generated', () => {
    const s = toSubmission(ws(), 'gen.pdf', true, { kind: 'upload' });
    expect(s.note).toContain('Filename generated by the web form; the original name was not usable.');
    expect(s.note).toContain('From the board packet.');
  });

  it('records the contributor name or anonymous', () => {
    expect(toSubmission(ws(), 'a.pdf', false, { kind: 'upload' }).retrievedBy).toBe('web form: Pat Smith');
    expect(toSubmission(ws({ name: null }), 'a.pdf', false, { kind: 'upload' }).retrievedBy).toBe('web form (anonymous)');
  });

  it('sanitizes the public-supplied name', () => {
    const s = toSubmission(ws({ name: '  Pat\n\t Smith\u0000$(rm -rf) ' }), 'a.pdf', false, { kind: 'upload' });
    expect(s.retrievedBy).toBe('web form: Pat Smith $(rm -rf)');
    expect(toSubmission(ws({ name: ' \n\t ' }), 'a.pdf', false, { kind: 'upload' }).retrievedBy).toBe('web form (anonymous)');
    expect(toSubmission(ws({ name: 'x'.repeat(500) }), 'a.pdf', false, { kind: 'upload' }).retrievedBy.length).toBeLessThanOrEqual(100);
  });

  it('maps to provenance that passes the schema', () => {
    const facts = { sha256: 'a'.repeat(64), bytes: 10 };
    for (const [w, how, gen] of [
      [ws(), { kind: 'upload' } as const, false],
      [ws({ name: null, sourceUrl: null, note: null }), LINK, true],
    ] as const) {
      const doc = buildProvenance(toSubmission(w, 'budget.pdf', gen, how), facts, null);
      expect(validateAgainst('provenance', doc)).toEqual([]);
    }
  });
});
