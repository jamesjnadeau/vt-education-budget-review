/** Maps a validated web submission onto the shared Submission the provenance builder takes. */
import type { Submission } from '../intake/submission.ts';
import type { WebSubmission } from './payload.ts';

export type Obtained = { kind: 'upload' } | { kind: 'link'; finalUrl: string; fetchedDate: string };

const MAX_NAME_CHARS = 80;

/** The name comes from the public: flatten whitespace and control characters, cap the length. */
function cleanName(name: string | null): string | null {
  if (name === null) return null;
  const flat = name.replace(/[\p{Cc}\s]+/gu, ' ').trim();
  const capped = flat.slice(0, MAX_NAME_CHARS).trim();
  return capped === '' ? null : capped;
}

export function toSubmission(ws: WebSubmission, filename: string, generatedName: boolean, how: Obtained): Submission {
  const parts: string[] = [];
  if (how.kind === 'link') {
    parts.push(
      `Sent through the web form. Contributor said: method ${ws.retrievalMethod}, date ${ws.retrievedDate}, ` +
        `source ${ws.sourceUrl ?? 'none'}.`,
    );
  }
  if (ws.note) parts.push(ws.note);
  if (generatedName) parts.push('Filename generated by the web form; the original name was not usable.');

  const name = cleanName(ws.name);
  return {
    entity: ws.entity,
    entityDir: ws.entityDir,
    fiscalYear: ws.fiscalYear,
    attachmentUrl: ws.source.kind === 'link' ? ws.source.url : `netlify-blobs:${ws.source.uploadId}`,
    filename,
    sourceUrl: how.kind === 'link' ? how.finalUrl : ws.sourceUrl,
    retrievedDate: how.kind === 'link' ? how.fetchedDate : ws.retrievedDate,
    retrievalMethod: how.kind === 'link' ? 'http-fetch' : ws.retrievalMethod,
    documentType: ws.documentType,
    note: parts.length > 0 ? parts.join(' ') : null,
    retrievedBy: name === null ? 'web form (anonymous)' : `web form: ${name}`,
  };
}
